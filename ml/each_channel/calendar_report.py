def pct(value):
    if value is None:
        return "—"
    return f"{100 * value:.3f}%" if 0 < abs(value) < 0.001 else f"{100 * value:.1f}%"


def pair(metrics):
    return f"{pct(metrics.get('precision'))} / {pct(metrics.get('recall'))}"


def bootstrap(frame, threshold, old_threshold, name, seed=42):
    y = frame.target.eq(1).to_numpy()
    new = frame[f"score_{name}"].to_numpy() >= threshold
    old = frame.score_incumbent.to_numpy() >= old_threshold
    counts = (
        pd.DataFrame(
            {
                "channel": frame.channel_id,
                "ntp": y & new,
                "nfp": ~y & new,
                "nfn": y & ~new,
                "otp": y & old,
                "ofp": ~y & old,
                "ofn": y & ~old,
            }
        )
        .groupby("channel")
        .sum()
        .to_numpy()
    )
    rng = np.random.default_rng(seed)
    values = []
    for _ in range(500):
        ntp, nfp, nfn, otp, ofp, ofn = counts[rng.integers(len(counts), size=len(counts))].sum(
            axis=0
        )
        p = ntp / (ntp + nfp) if ntp + nfp else np.nan
        r = ntp / (ntp + nfn) if ntp + nfn else np.nan
        op = otp / (otp + ofp) if otp + ofp else np.nan
        ore = otp / (otp + ofn) if otp + ofn else np.nan
        values.append([p, r, p - op, r - ore])
    result = {}
    for j, key in enumerate(("precision", "recall", "delta_precision", "delta_recall")):
        sample = np.array(values)[:, j]
        sample = sample[np.isfinite(sample)]
        result[key] = np.quantile(sample, [0.025, 0.975]).tolist() if len(sample) else None
    return result


