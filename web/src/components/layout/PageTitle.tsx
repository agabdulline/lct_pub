export function PageTitle() {
  const { pathname } = useLocation()
  const { run, history, all } = useRun()
  const page = PAGES.find((p) => p.match(pathname))
  if (!page) return null
  return (
    <div className="flex min-w-0 items-center gap-1">
      <h1 className="truncate text-sm font-semibold sm:text-base">{page.title}</h1>
      <PageInfo>{(all && page.all) || (history && page.history) || (run?.dataset && page.dataset) || page.info}</PageInfo>
    </div>
  )
}
