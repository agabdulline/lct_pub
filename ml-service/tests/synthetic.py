"""Синтетический объект для тестов — данных хакатона в тестах нет.

Объект 1, четыре дымовых канала: 11 (ПК10), 12 (ПК11), 13 (ПК12), 14 (ПК50). Каждый день у всех «Норма».
- день 20, 10:00 — тревога канала 11, соседи молчат; в 11:00 у него «Неисправен» → положительное решение;
- день 20, 10:30 — вторая тревога канала 11 → пропуск decided_within_24h;
- день 30, 09:00/09:01/09:02 — тревоги 12, 13, 14; у 13 сосед по пикету 12 сработал минутой раньше;
- день 35, 12:00 — «Неисправен» у 12, в 12:30 его тревога → пропуск fault_recent_24h;
- день 3 — тревога канала 14 → пропуск history_lt_7d.
"""

import pandas as pd

BASE = pd.Timestamp("2025-03-03")  # понедельник


def at(day: int, hh: int = 0, mm: int = 0) -> pd.Timestamp:
    return BASE + pd.Timedelta(days=day, hours=hh, minutes=mm)


def channels() -> pd.DataFrame:
    return pd.DataFrame(
        {
            "channel_id": [11, 12, 13, 14],
            "object_id": [1, 1, 1, 1],
            "sensor_type": ["Датчик дыма"] * 4,
            "tag": ["1-1.1.1.1.", "1-1.1.1.2.", "1-1.1.1.3.", "1-1.1.2.1."],
            "picket_number": [10, 11, 12, 50],
        }
    )


def events() -> pd.DataFrame:
    rows = [(c, at(d, 6), "Норма") for c in (11, 12, 13, 14) for d in range(0, 41)]
    rows += [
        (11, at(20, 10), "Обнаружен дым"),
        (11, at(20, 10, 30), "Обнаружен дым"),
        (11, at(20, 11), "Неисправен"),
        (12, at(30, 9), "Обнаружен дым"),
        (13, at(30, 9, 1), "Обнаружен дым"),
        (14, at(30, 9, 2), "Обнаружен дым"),
        (12, at(35, 12), "Неисправен"),
        (12, at(35, 12, 30), "Обнаружен дым"),
        (14, at(3, 10), "Обнаружен дым"),
    ]
    ev = pd.DataFrame(rows, columns=["channel_id", "ts", "value"])
    ev["event_id"] = range(len(ev))
    return ev.sort_values(["channel_id", "ts"]).reset_index(drop=True)
